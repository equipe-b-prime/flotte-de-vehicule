-- Site
CREATE TABLE IF NOT EXISTS site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    ville VARCHAR(255) NOT NULL,
    adresse VARCHAR(255) NOT NULL,
    CONSTRAINT uk_site_nom UNIQUE (nom)
);

-- Contrat
CREATE TABLE IF NOT EXISTS contrat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_contrat VARCHAR(255),
    duree_mois INTEGER DEFAULT 0,
    loyer_mensuel NUMERIC(38, 2),
    km_autorise INTEGER DEFAULT 0
);

-- État d'affectation
CREATE TABLE IF NOT EXISTS etat_affectation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    libelle VARCHAR(255),
    CONSTRAINT uk_etat_affectation_code UNIQUE (code)
);

-- Salarié
CREATE TABLE IF NOT EXISTS salarie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255),
    prenom VARCHAR(255),
    matricule VARCHAR(255) NOT NULL,
    service VARCHAR(255),
    CONSTRAINT uk_salarie_matricule UNIQUE (matricule)
);

-- Prestataire
CREATE TABLE IF NOT EXISTS prestataire (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL
);

-- Type d'entretien
CREATE TABLE IF NOT EXISTS type_entretien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(255) NOT NULL,
    est_regulier BOOLEAN DEFAULT TRUE,
    CONSTRAINT uk_type_entretien_libelle UNIQUE (libelle)
);

-- Type de dépense
CREATE TABLE IF NOT EXISTS type_depense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(255) NOT NULL,
    CONSTRAINT uk_type_depense_libelle UNIQUE (libelle)
);

-- Véhicule
CREATE TABLE IF NOT EXISTS vehicule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255),
    immatriculation VARCHAR(255) NOT NULL,
    marque VARCHAR(255),
    modele VARCHAR(255),
    date_mise_en_circulation TIMESTAMP(6) WITHOUT TIME ZONE,
    site_id BIGINT,
    contrat_id BIGINT,
    etat_affectation_id BIGINT,
    kilometrage_actuel INTEGER DEFAULT 0,
    CONSTRAINT uk_vehicule_immatriculation UNIQUE (immatriculation),
    CONSTRAINT fk_vehicule_site FOREIGN KEY (site_id) REFERENCES site(id),
    CONSTRAINT fk_vehicule_contrat FOREIGN KEY (contrat_id) REFERENCES contrat(id),
    CONSTRAINT fk_vehicule_etat_affectation FOREIGN KEY (etat_affectation_id) REFERENCES etat_affectation(id)
);

-- Affectation
CREATE TABLE IF NOT EXISTS affectation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_debut TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    date_fin TIMESTAMP(6) WITHOUT TIME ZONE,
    kilometrage_restitution INTEGER,
    salarie_id BIGINT,
    vehicule_id BIGINT,
    CONSTRAINT fk_affectation_salarie FOREIGN KEY (salarie_id) REFERENCES salarie(id),
    CONSTRAINT fk_affectation_vehicule FOREIGN KEY (vehicule_id) REFERENCES vehicule(id)
);

-- Entretien
CREATE TABLE IF NOT EXISTS entretien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_intervention TIMESTAMP(6) WITHOUT TIME ZONE,
    cout NUMERIC(38, 2),
    duree_immobilisatin INTEGER DEFAULT 0,
    kilometrage BIGINT,
    vehicule_id BIGINT,
    type_entretien_id BIGINT,
    prestataire_id BIGINT,
    CONSTRAINT fk_entretien_vehicule FOREIGN KEY (vehicule_id) REFERENCES vehicule(id),
    CONSTRAINT fk_entretien_type FOREIGN KEY (type_entretien_id) REFERENCES type_entretien(id),
    CONSTRAINT fk_entretien_prestataire FOREIGN KEY (prestataire_id) REFERENCES prestataire(id)
);

-- Dépense
CREATE TABLE IF NOT EXISTS depense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_depense TIMESTAMP(6) WITHOUT TIME ZONE,
    montant_depense NUMERIC(38, 2),
    affectation_id BIGINT,
    type_depense_id BIGINT,
    CONSTRAINT fk_depense_affectation FOREIGN KEY (affectation_id) REFERENCES affectation(id),
    CONSTRAINT fk_depense_type FOREIGN KEY (type_depense_id) REFERENCES type_depense(id)
);

-- Trajet
CREATE TABLE IF NOT EXISTS trajet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    km_depart INTEGER DEFAULT 0,
    km_arrivee INTEGER DEFAULT 0,
    date_trajet TIMESTAMP(6) WITHOUT TIME ZONE,
    motif VARCHAR(255),
    affectation_id BIGINT,
    CONSTRAINT fk_trajet_affectation FOREIGN KEY (affectation_id) REFERENCES affectation(id)
);

