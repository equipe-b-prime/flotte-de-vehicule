-- Vue 1 : Statistiques globales par véhicule
CREATE OR REPLACE VIEW v_vehicule_stats AS
SELECT
    v.id AS vehicule_id,
    COALESCE(a.nb_affectations, 0::bigint) AS nb_affectations,
    COALESCE(e.nb_entretiens, 0::bigint) AS nb_entretiens,
    COALESCE(e.cout_total, 0::numeric) AS cout_total_entretiens,
    COALESCE(e.jours_immobilises, 0::bigint) AS jours_immobilises,
    e.premier_entretien,
    e.dernier_entretien
FROM vehicule v
LEFT JOIN (
    SELECT affectation.vehicule_id, count(*) AS nb_affectations
    FROM affectation
    GROUP BY affectation.vehicule_id
) a ON a.vehicule_id = v.id
LEFT JOIN (
    SELECT
        entretien.vehicule_id,
        count(*) AS nb_entretiens,
        COALESCE(sum(entretien.cout), 0::numeric) AS cout_total,
        COALESCE(sum(entretien.duree_immobilisatin), 0::bigint) AS jours_immobilises,
        min(entretien.date_intervention) AS premier_entretien,
        max(entretien.date_intervention) AS dernier_entretien
    FROM entretien
    GROUP BY entretien.vehicule_id
) e ON e.vehicule_id = v.id;

-- Vue 2 : Répartition des coûts d'entretien par type et par véhicule
CREATE OR REPLACE VIEW v_vehicule_cout_type AS
SELECT
    ROW_NUMBER() OVER (ORDER BY v.id, te.id)::bigint AS id,
    v.id AS vehicule_id,
    te.id AS type_entretien_id,
    te.libelle,
    count(e.id)::bigint AS nb_entretiens,
    COALESCE(sum(e.cout), 0::numeric) AS cout_total
FROM vehicule v
JOIN entretien e ON e.vehicule_id = v.id
JOIN type_entretien te ON te.id = e.type_entretien_id
GROUP BY v.id, te.id, te.libelle;

-- Vue 3 : Kilométrage mensuel parcouru par site et par véhicule
CREATE OR REPLACE VIEW v_km_site_mensuel AS
SELECT
    ROW_NUMBER() OVER (ORDER BY v.id, date_trunc('month', t.date_trajet))::bigint AS id,
    v.id AS vehicule_id,
    v.site_id,
    date_trunc('month', t.date_trajet)::timestamp without time zone AS mois,
    COALESCE(sum(t.km_arrivee - t.km_depart), 0::bigint) AS km_parcouru
FROM trajet t
JOIN affectation a ON a.id = t.affectation_id
JOIN vehicule v ON v.id = a.vehicule_id
GROUP BY v.id, v.site_id, date_trunc('month', t.date_trajet);
